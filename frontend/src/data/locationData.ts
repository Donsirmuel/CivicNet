const normalize = (value: string): string => value.trim().toLowerCase();

// Lookups accept either the generated id (e.g. "lagos", "ikeja") or the plain
// name the backend stores (e.g. "Lagos", "Ikeja"), so both resolve cleanly.
export const getStateById = (stateId: string): State | undefined => {
  if (!stateId) return undefined;
  const key = normalize(stateId);
  return nigeriaLocationData.find((state) => state.id === key || normalize(state.name) === key);
};

export const getLGAById = (stateId: string, lgaId: string): LGA | undefined => {
  if (!lgaId) return undefined;
  const state = getStateById(stateId);
  if (!state) return undefined;
  const key = normalize(lgaId);
  return state.lgas.find((lga) => lga.id === key || normalize(lga.name) === key);
};

export const getWardById = (stateId: string, lgaId: string, wardId: string): Ward | undefined => {
  if (!wardId) return undefined;
  const lga = getLGAById(stateId, lgaId);
  if (!lga) return undefined;
  const key = normalize(wardId);
  return lga.wards.find((ward) => ward.id === key || normalize(ward.name) === key);
};

export const getLocationString = (location: { ward?: string; lga?: string; state?: string }): string => {
  const state = location.state ? getStateById(location.state) : undefined;
  const lga = location.lga ? getLGAById(location.state ?? '', location.lga) : undefined;
  const ward = location.ward ? getWardById(location.state ?? '', location.lga ?? '', location.ward) : undefined;

  // The ward may be a typed-in name that is not in our list — keep it either way.
  const wardName = ward?.name ?? location.ward?.trim() ?? '';

  if (state && lga) {
    return wardName ? `${wardName}, ${lga.name}, ${state.name}` : `${lga.name}, ${state.name}`;
  }
  if (state) {
    return lga ? `${lga.name}, ${state.name}` : state.name;
  }

  const rawParts = [location.ward, location.lga, location.state].filter(
    (value) => value && value.trim().length > 0,
  );
  return rawParts.length > 0 ? rawParts.join(', ') : 'Location pending';
};

export const getLocationCoordinates = (location?: { ward?: string; lga?: string; state?: string }): Coordinates | null => {
  if (!location?.state) return null;

  if (location.ward && location.lga) {
    const ward = getWardById(location.state, location.lga, location.ward);
    if (ward?.coordinates) return ward.coordinates;
  }
  if (location.lga) {
    const lga = getLGAById(location.state, location.lga);
    if (lga?.coordinates) return lga.coordinates;
  }
  const state = getStateById(location.state);
  return state?.coordinates ?? null;
};
